"""Match Duel Links card lines to Master Duel cards (systems: voice_tables).

  gen_voice_tables.py <transcripts.tsv> [review.tsv]

The transcripts (clip key -> text, from tools/transcribe_dl.py over categories 08/09/13) usually say the card's name
("I activate Multiply!", "Come forth, Elemental HERO Neos!"). Each line is fuzzy-matched against the Master Duel
card names in research/carddata; a confident match becomes a row of
fabric/src/main/resources/data/duelcraft/dl/card_lines.tsv (numbers only: character, category, sub, index, cid).
The optional review file adds the transcript and the card name for checking by hand; it is research only.
"""
import os
import re
import struct
import sys
from collections import defaultdict

from rapidfuzz import fuzz, process

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "research", "carddata")
OUT = os.path.join(ROOT, "fabric", "src", "main", "resources", "data", "duelcraft", "dl", "card_lines.tsv")
CUTOFF = 88  # partial_ratio score a match needs
MIN_LEN = 5  # shorter names must appear as whole words
# card names that are everyday duel talk and match lines that are not about the card
STOP = {"go", "attack", "draw", "turn", "end", "duel", "monster", "summon", "trap", "magic", "now", "come", "the", "you",
        "my", "this", "card", "go go", "yes", "no", "ha", "time", "power", "destiny", "victory", "battle"}


def norm(s):
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", " ", s.lower().replace("-", " "))).strip()


def playable():
    """Master Duel ids DuelCraft can duel with (an EDOPro passcode in md/cards.tsv)."""
    ok = set()
    for l in open(os.path.join(ROOT, "fabric", "src", "main", "resources", "data", "duelcraft", "md", "cards.tsv"), encoding="utf-8"):
        f = l.split("\t")
        if not l.startswith("#") and len(f) > 1 and f[1].strip() not in ("", "0"):
            ok.add(int(f[0]))
    return ok


def card_names():
    rd = lambda n: open(os.path.join(R, n + ".bin"), "rb").read()
    ok = playable()
    idx, names, prop = rd("card_indx"), rd("card_name"), rd("card_prop")
    out = {}
    for i in range(len(prop) // 8):
        a1, = struct.unpack_from("<I", prop, i * 8)
        o, = struct.unpack_from("<I", idx, i * 8)
        name = names[o:names.index(b"\0", o)].decode("utf-8", "replace")
        n = norm(name)
        # 'Spell Card "Monster Reborn"' would swallow every "I activate the spell card, Monster Reborn!"
        if n.startswith(("spell card ", "trap card ")):
            continue
        if n and n not in STOP and n not in out and (a1 & 0xFFFF) in ok:
            out[n] = (a1 & 0xFFFF, name)
    return out


def best(text, names, keys):
    t = norm(text)
    if not t:
        return None
    hits = process.extract(t, keys, scorer=fuzz.partial_ratio, limit=12, score_cutoff=CUTOFF)
    # a name said word for word wins: the one said last (summon chants end on the name), then the longest
    exact = []
    for k, _, _ in hits:
        for m in re.finditer(r"\b" + re.escape(k) + r"\b", t):
            exact.append((m.end(), len(k), k))
    if exact:
        return names[max(exact)[2]]
    good = []
    for key, score, _ in hits:
        if len(key) > len(t) + 3:
            continue  # the line must contain the name, not the other way round ("You" is not a card)
        if len(key) < MIN_LEN or len(key.split()) == 1:
            continue  # one-word and short names count only when said word for word (handled above)
        good.append((round(score), len(key), key))
    if not good:
        return None
    good.sort(reverse=True)
    return names[good[0][2]]


def main():
    tx, review = sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None
    names = card_names()
    keys = list(names)
    lines = defaultdict(dict)  # (ch, cat, sub, idx) -> part -> text
    for l in open(tx, encoding="utf-8"):
        f = l.rstrip("\n").split("\t")
        if len(f) < 2:
            continue
        m = re.match(r"v(\d{4})_(\d{2})_(\d{2})_(\d{2})_(\d)$", f[0])
        if m and m.group(2) in ("08", "09", "13"):
            lines[(int(m.group(1)), m.group(2), m.group(3), m.group(4))][int(m.group(5))] = f[1]
    rows, rev = [], []
    for key in sorted(lines):
        parts = [lines[key][p] for p in sorted(lines[key])]
        hit = best(" ".join(parts), names, keys)
        if hit:
            rows.append((*key, hit[0]))
        rev.append((*key, hit[0] if hit else 0, hit[1] if hit else "", " | ".join(parts)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as o:
        o.write("# Duel Links card lines -> Master Duel card id. Generated by tools/gen_voice_tables.py; numbers only.\n")
        o.write("# character\tcategory\tsub\tindex\tcid\n")
        for ch, cat, sub, ix, cid in rows:
            o.write(f"{ch}\t{cat}\t{sub}\t{ix}\t{cid}\n")
    if review:
        with open(review, "w", encoding="utf-8", newline="\n") as o:
            for r in rev:
                o.write("\t".join(map(str, r)) + "\n")
    print(f"{len(rows)} of {len(lines)} lines matched, {len({r[0] for r in rows})} characters -> {OUT}")


if __name__ == "__main__":
    main()
