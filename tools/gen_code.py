src += "/** One method per ai_policies row; DuelAi implements them. Each returns the raw response bytes. */\npublic interface AiPolicies {\n"
by_policy = {}
for p in S["duel_prompts"]:
    by_policy.setdefault(p["aiPolicy"], []).append(p["record"])
for r in S["ai_policies"]:
    for rec in by_policy[r["id"]]:
        src += f"\t/** {r['id']}: {r['rule']} Fallback: {r['fallback']} */\n\tbyte[] {camel(r['id'])}({rec} p, boolean fallback);\n\n"
src += "\tdefault byte[] answer(Prompt p, boolean fallback) {\n\t\treturn switch (p) {\n"
for r in S["duel_prompts"]:
    src += f"\t\t\tcase {r['record']} x -> {camel(r['aiPolicy'])}(x, fallback);\n"
src += "\t\t};\n\t}\n}\n"
write(MAIN, "AiPolicies.java", src)

