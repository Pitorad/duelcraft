"""Generates Java from the design sheets: one record/entry/method per row. Run after preflight.

    python -I tools/gen_code.py
Outputs (overwritten every run; never edit by hand):
  fabric/src/main/java/dev/duelcraft/gen/   Settings, MdEncodings, Prompts, Events, Payloads, Decks,
                                            MobDuelists, AiPolicies, ItemSpecs, HookIds, MdAssets
  fabric/src/client/java/dev/duelcraft/client/gen/PromptWidgets.java
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "design")
MAIN = os.path.join(ROOT, "fabric", "src", "main", "java", "dev", "duelcraft", "gen")
CLIENT = os.path.join(ROOT, "fabric", "src", "client", "java", "dev", "duelcraft", "client", "gen")
S = {f[:-5]: json.load(open(os.path.join(D, f), encoding="utf-8"))["rows"] for f in os.listdir(D) if f.endswith(".json")}
HDR = "// GENERATED by tools/gen_code.py from design/{sheet}.json - do not edit.\n"


def camel(s, upper=False):
    parts = re.split(r"[_\W]+", s)
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return out[:1].upper() + out[1:] if upper else out


def jstr(s):
    return json.dumps(s, ensure_ascii=False)


def write(dirpath, name, text):
    os.makedirs(dirpath, exist_ok=True)
    with open(os.path.join(dirpath, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# ---------------------------------------------------------------- layouts -> records + decoders
JT = {"u8": "int", "u16": "int", "u32": "int", "i32": "int", "u64": "long", "loc": "Loc"}
RD = {"u8": "r.u8()", "u16": "r.u16()", "u32": "r.u32()", "i32": "r.i32()", "u64": "r.u64()", "loc": "r.loc()"}


def parse_layout(s):
    """'a:u8, l:list<u32>[x:u32,y:loc]' -> [(name, type, sub)]"""
    fields, i, s = [], 0, s.strip()
    while i < len(s):
        m = re.compile(r"\s*(\w+):(list<(\w+)>\[|(\w+))").match(s, i)
        name = m.group(1)
        if m.group(3):
            depth, j = 1, m.end()
            while depth:
                depth += {"[": 1, "]": -1}.get(s[j], 0)
                j += 1
            fields.append((name, "list", (m.group(3), parse_layout(s[m.end():j - 1]))))
            i = j
        else:
            fields.append((name, m.group(4), None))
            i = m.end()
        m2 = re.compile(r"\s*,?").match(s, i)
        i = m2.end()
    return fields


def gen_record(rec, fields, iface, indent="\t"):
    """returns (java source of record with static read(MsgReader r))"""
    out, comps, reads = [], [], []
    for name, t, sub in fields:
        if t == "list":
            ct, subf = sub
            sub_name = camel(name, True) + "Entry"
            out.append(gen_record(sub_name, subf, None, indent + "\t"))
            comps.append(f"java.util.List<{sub_name}> {name}")
            reads.append(f"r.list(r.{'u8' if ct == 'u8' else 'u32'}(), {sub_name}::read)")
        else:
            comps.append(f"{JT[t]} {name}")
            reads.append(RD[t])
    impl = f" implements {iface}" if iface else ""
    body = f"{indent}public record {rec}({', '.join(comps)}){impl} {{\n"
    body += "".join(out)
    body += f"{indent}\tpublic static {rec} read(MsgReader r) {{\n{indent}\t\treturn new {rec}({', '.join(reads)});\n{indent}\t}}\n"
    body += f"{indent}}}\n"
    return body


def gen_messages(sheet, cls, iface, extra):
    rows = S[sheet]
    src = HDR.format(sheet=sheet) + "package dev.duelcraft.gen;\n\nimport dev.duelcraft.duel.MsgReader;\nimport dev.duelcraft.duel.MsgReader.Loc;\n\n"
    src += f"public final class {cls} {{\n\tprivate {cls}() {{}}\n\n\tpublic sealed interface {iface} permits {', '.join(r['record'] for r in rows)} {{\n\t\tint msgId();\n\t}}\n\n"
    for r in rows:
        rec = gen_record(r["record"], parse_layout(r["layout"]), iface)
        # add msgId() + metadata to the record
        meta = f"\t\t@Override public int msgId() {{ return {r['msgId']}; }}\n"
        for k in extra:
            meta += f"\t\tpublic static final String {k.upper()} = {jstr(str(r[k]))};\n"
        rec = rec.replace(f"implements {iface} {{\n", f"implements {iface} {{\n{meta}", 1)
        src += rec + "\n"
    src += f"\t/** Decodes one message body (after the id byte); null when this sheet has no row for the id. */\n"
    src += f"\tpublic static {iface} decode(int msgId, MsgReader r) {{\n\t\treturn switch (msgId) {{\n"
    for r in rows:
        src += f"\t\t\tcase {r['msgId']} -> {r['record']}.read(r);\n"
    src += "\t\t\tdefault -> null;\n\t\t};\n\t}\n\n"
    for k in extra:
        src += f"\tpublic static String {camel(k)}(int msgId) {{\n\t\treturn switch (msgId) {{\n"
        for r in rows:
            src += f"\t\t\tcase {r['msgId']} -> {jstr(str(r[k]))};\n"
        src += "\t\t\tdefault -> null;\n\t\t};\n\t}\n\n"
    src += "\tpublic static String name(int msgId) {\n\t\treturn switch (msgId) {\n"
    for r in rows:
        src += f"\t\t\tcase {r['msgId']} -> {jstr(r['name'])};\n"
    src += "\t\t\tdefault -> \"MSG_\" + msgId;\n\t\t};\n\t}\n}\n"
    write(MAIN, cls + ".java", src)


