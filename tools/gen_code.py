# ---------------------------------------------------------------- payloads
TYPES = {"int": ("int", "buf.writeVarInt({v})", "buf.readVarInt()"), "long": ("long", "buf.writeLong({v})", "buf.readLong()"),
         "bool": ("boolean", "buf.writeBoolean({v})", "buf.readBoolean()"), "string": ("String", "buf.writeUtf({v})", "buf.readUtf()"),
         "bytes": ("byte[]", "buf.writeByteArray({v})", "buf.readByteArray()")}
src = HDR.format(sheet="payloads") + """package dev.duelcraft.gen;

import net.minecraft.network.RegistryFriendlyByteBuf;
import net.minecraft.network.codec.StreamCodec;
import net.minecraft.network.protocol.common.custom.CustomPacketPayload;
import net.minecraft.resources.Identifier;

public final class Payloads {
\tprivate Payloads() {}

"""
for r in S["payloads"]:
    fs = [f.strip().split(":") for f in r["fields"].split(",")]
    comps = ", ".join(f"{TYPES[t][0]} {n}" for n, t in fs)
    wr = "".join(f"\t\t\t\t{TYPES[t][1].format(v='p.' + n + '()')};\n" for n, t in fs)
    rd = ", ".join(TYPES[t][2] for n, t in fs)
    src += f"""\t/** {r['direction']}, handled by {r['handler']}. */
\tpublic record {r['record']}({comps}) implements CustomPacketPayload {{
\t\tpublic static final Type<{r['record']}> TYPE = new Type<>(Identifier.fromNamespaceAndPath("duelcraft", {jstr(r['id'])}));
\t\tpublic static final boolean TO_CLIENT = {str(r['direction'] == 's2c').lower()};
\t\tpublic static final StreamCodec<RegistryFriendlyByteBuf, {r['record']}> CODEC = StreamCodec.of(
\t\t\t(buf, p) -> {{
{wr}\t\t\t}},
\t\t\tbuf -> new {r['record']}({rd}));

\t\t@Override
\t\tpublic Type<? extends CustomPacketPayload> type() {{
\t\t\treturn TYPE;
\t\t}}
\t}}

"""
write(MAIN, "Payloads.java", src + "}\n")

